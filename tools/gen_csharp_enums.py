#!/usr/bin/env python3
"""Generate ImGuiEnums.g.cs from third_party/imgui/imgui.h.

Parses every `enum ImGuiXxx_ { ... }` (and the typed enums ImGuiDir/ImGuiKey/...)
and emits a C# enum with the same member names minus the `ImGuiXxx_` prefix plus
an `ImGuiXxx` enum name. Values are evaluated from the C++ source.
"""
import re
import sys
from pathlib import Path

ENUM_RE = re.compile(r'enum\s+(ImGui\w+)\s*(?::\s*\w+\s*)?\{(.*?)\n\};', re.S)
ENTRY_RE = re.compile(r'^\s*(ImGui\w+)\s*(?:=\s*(.*?))?\s*$')


def strip_comments(text: str) -> str:
    out = []
    i = 0
    n = len(text)
    while i < n:
        c = text[i]
        if c == '"':
            out.append(c)
            i += 1
            while i < n:
                out.append(text[i])
                if text[i] == '\\':
                    i += 1
                    if i < n:
                        out.append(text[i])
                elif text[i] == '"':
                    i += 1
                    break
                i += 1
            continue
        if c == '/' and i + 1 < n and text[i + 1] == '/':
            while i < n and text[i] != '\n':
                i += 1
            continue
        if c == '/' and i + 1 < n and text[i + 1] == '*':
            i += 2
            while i + 1 < n and not (text[i] == '*' and text[i + 1] == '/'):
                i += 1
            i += 2
            continue
        out.append(c)
        i += 1
    return ''.join(out)


class Evaluator:
    def __init__(self):
        self.symbols = {}

    def eval(self, expr: str):
        expr = expr.strip()
        if not expr:
            return None
        # replace identifiers with known values
        def repl(m):
            name = m.group(0)
            if name in self.symbols:
                return str(self.symbols[name])
            if name in ('true', 'false'):
                return '1' if name == 'true' else '0'
            raise KeyError(name)
        try:
            tokens = re.sub(r'\b(ImGui\w+|true|false)\b', repl, expr)
            # char literal -> integer
            tokens = re.sub(r"'(.)'", lambda m: str(ord(m.group(1))), tokens)
            tokens = tokens.replace('/', '//')
            return int(eval(tokens, {'__builtins__': {}}, {}))
        except Exception as exc:
            raise ValueError(f'cannot evaluate {expr!r}: {exc}')


def parse_enum(name: str, body: str, evaluator: Evaluator):
    members = []
    for raw in split_top_level(body):
        entry = raw.strip()
        if not entry:
            continue
        m = ENTRY_RE.match(entry)
        if not m:
            raise ValueError(f'{name}: bad entry {entry!r}')
        member = m.group(1)
        expr = m.group(2)
        if expr is None:
            value = 0 if not members else members[-1][1] + 1
        else:
            value = evaluator.eval(expr)
        members.append((member, value))
        evaluator.symbols[member] = value
    return members


def split_top_level(body: str):
    parts = []
    depth = 0
    cur = []
    for ch in body:
        if ch == '(':
            depth += 1
        elif ch == ')':
            depth -= 1
        if ch == ',' and depth == 0:
            parts.append(''.join(cur))
            cur = []
        else:
            cur.append(ch)
    parts.append(''.join(cur))
    return parts


def main():
    if len(sys.argv) < 3:
        print('usage: gen_csharp_enums.py <imgui.h> <out.cs>')
        return 1
    header = Path(sys.argv[1]).read_text(encoding='utf-8', errors='replace')
    header = strip_comments(header)
    # Drop preprocessor directives (obsolete blocks keep their aliases; harmless).
    header = '\n'.join(line for line in header.splitlines()
                       if not line.lstrip().startswith('#'))

    evaluator = Evaluator()
    blocks = []
    for m in ENUM_RE.finditer(header):
        name = m.group(1)
        if not name.endswith('_') and name not in ('ImGuiDir', 'ImGuiKey', 'ImGuiMouseSource', 'ImGuiSortDirection'):
            # skip internal / non-flag enums we do not wrap
            continue
        try:
            members = parse_enum(name, m.group(2), evaluator)
        except Exception as exc:
            print(f'warning: {exc}', file=sys.stderr)
            continue
        if not members:
            continue
        blocks.append((name.rstrip('_'), members))

    lines = [
        '// <auto-generated>',
        '// Generated by tools/gen_csharp_enums.py from Dear ImGui imgui.h.',
        '// Do not edit by hand.',
        '// </auto-generated>',
        'namespace EthhhSDK',
        '{',
    ]
    for name, members in blocks:
        prefix = name + '_'
        underlying = 'uint' if any(v < 0 or v > 0x7FFFFFFF for _, v in members) else 'int'
        lines.append(f'    public enum {name} : {underlying}')
        lines.append('    {')
        for member, value in members:
            short = member[len(prefix):] if member.startswith(prefix) else member
            if not short or short[0].isdigit():
                short = 'Key' + short
            short = re.sub(r'[^A-Za-z0-9_]', '_', short)
            if underlying == 'uint':
                lines.append(f'        {short} = 0x{value & 0xFFFFFFFF:08X}u,')
            else:
                lines.append(f'        {short} = {value},')
        lines.append('    }')
        lines.append('')
    lines.append('}')
    out = Path(sys.argv[2])
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print(f'wrote {out} ({len(blocks)} enums)')
    return 0


if __name__ == '__main__':
    sys.exit(main())
