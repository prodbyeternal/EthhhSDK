#!/usr/bin/env python3
"""Generate an MSVC .def file with undecorated C exports.

Every export in EthhhSDK is declared through the ETH_CAPI macro in the core
sources, using the form:

    ETH_CAPI(int, EthGame_TickCount, (void))

This script scans the given sources for those declarations and writes a plain
EXPORTS list so P/Invoke sees tidy names (no stdcall @N decoration).
"""
import argparse
import re
import sys
from pathlib import Path

CAPI_RE = re.compile(
    r"ETH_CAPI\s*\(\s*[^,]+,\s*([A-Za-z_][A-Za-z0-9_]*)\s*,",
    re.MULTILINE,
)

# Exports that do not go through ETH_CAPI.
ALWAYS = [
    "EthhhSDK_EntryGate",
]

HEADER = """\
; Auto-generated by tools/gen_def.py -- do not edit.
LIBRARY EthhhSDK
EXPORTS
"""


def collect(files):
    names = []
    seen = set()

    def add(name):
        if name not in seen:
            seen.add(name)
            names.append(name)

    for f in files:
        text = Path(f).read_text(encoding="utf-8", errors="replace")
        for m in CAPI_RE.finditer(text):
            add(m.group(1))
    for name in ALWAYS:
        add(name)
    return names


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("sources", nargs="+")
    ap.add_argument("-o", "--output", required=True)
    args = ap.parse_args(argv)

    names = collect(args.sources)
    if len(names) <= len(ALWAYS):
        print("gen_def: warning: no ETH_CAPI exports found", file=sys.stderr)

    out = HEADER
    for name in names:
        out += "    %s\n" % name

    Path(args.output).write_text(out, encoding="ascii", newline="\r\n")
    print("gen_def: %d exports -> %s" % (len(names), args.output))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
